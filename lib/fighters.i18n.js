/**
 * Retrieve a localized field from fighter data.
 * Falls back to the English base data when no translation exists.
 */
export function getLocalizedField(fighter, field, locale, subField = null) {
  if (locale === "en") {
    return subField ? fighter[field]?.[subField] : fighter[field];
  }
  const t = FIGHTER_TRANSLATIONS[fighter.id]?.[locale];
  if (!t) return subField ? fighter[field]?.[subField] : fighter[field];
  if (subField) return t[field]?.[subField] ?? fighter[field]?.[subField];
  return t[field] ?? fighter[field];
}

/**
 * Merge translated combo names into a combo list, keeping steps in English.
 */
export function getLocalizedCombos(fighter, locale) {
  if (locale === "en") return fighter.signatureCombos;
  const t = FIGHTER_TRANSLATIONS[fighter.id]?.[locale];
  if (!t?.signatureCombos) return fighter.signatureCombos;
  return fighter.signatureCombos.map((combo, i) => ({
    ...combo,
    name: t.signatureCombos[i]?.name ?? combo.name,
  }));
}

/**
 * Merge translated fight notes, keeping fight name + year in English.
 */
export function getLocalizedFights(fighter, locale) {
  if (locale === "en") return fighter.famousFights;
  const t = FIGHTER_TRANSLATIONS[fighter.id]?.[locale];
  if (!t?.famousFights) return fighter.famousFights;
  return fighter.famousFights.map((f, i) => ({
    ...f,
    note: t.famousFights[i]?.note ?? f.note,
  }));
}
